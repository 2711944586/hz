# 2.5 把原文中的"摘要"、"目录"、"第一部分"、"第二部分"、"第三部分" 段落
#     改为正确的 Heading 1 样式，让目录与页眉能识别
def _promote_headings():
    targets = {'摘要', '目录', '第一部分  会展发展情况', '第二部分  存在问题', '第三部分  建议'}
    # 也匹配单空格变体
    targets_normalized = set()
    for t in targets:
        targets_normalized.add(t)
        targets_normalized.add(t.replace('  ', ' '))
        targets_normalized.add(t.replace(' ', ''))
    h1_targets = ['一、', '二、', '三、', '四、', '五、', '六、', '七、', '八、', '九、', '十、', '十一、', '十二、', '十三、', '十四、']
    for p in doc.paragraphs:
        text = p.text.strip()
        if not text:
            continue  # 空段落不动
        norm = text.replace(' ', '')
        if any(norm == t.replace(' ', '') for t in targets):
            try:
                p.style = doc.styles['Heading 1']
            except Exception:
                pass
        # 二级标题：以"一、"等开头但不太长的
        elif any(text.startswith(prefix) for prefix in h1_targets) and len(text) < 30:
            try:
                p.style = doc.styles['Heading 2']
            except Exception:
                pass
        # 三级标题：以"（一）"等开头
        elif text.startswith('（') and len(text) < 30:
            for x in ['（一）','（二）','（三）','（四）','（五）','（六）','（七）','（八）','（九）','（十）']:
                if text.startswith(x):
                    try:
                        p.style = doc.styles['Heading 3']
                    except Exception:
                        pass
                    break

_promote_headings()


# 2.6 给所有正文段落统一字体（中文宋体小四，行距 1.5，首行缩进 2 字）
def _apply_body_format():
    from style_helper import _ce
    for p in doc.paragraphs:
        if p.style.name in ('Heading 1', 'Heading 2', 'Heading 3'):
            continue
        # 行距与首行缩进
        pf = p.paragraph_format
        if pf.line_spacing is None:
            pf.line_spacing = 1.5
        # 仅对实际有文字的段落加首行缩进，且不是单纯的列表项（用 □/·/数字 开头不缩进）
        text = p.text.strip()
        if text and not text.startswith(('□', '·', '-', '•', '注：', '（在线', '关键词')):
            # 只有当前没有缩进时才设
            if pf.first_line_indent in (None,):
                pf.first_line_indent = Cm(0.74)
        # 字体（保留原有黑体等，不强制改）
        for run in p.runs:
            if not run.font.size:
                run.font.size = Pt(12)
            run.font.name = run.font.name or 'Times New Roman'
            rpr = run._element.get_or_add_rPr()
            rfonts = rpr.find(qn('w:rFonts'))
            if rfonts is None:
                rfonts = _ce('w:rFonts')
                rpr.append(rfonts)
            # 中文用宋体（如果已设黑体则保持）
            if not rfonts.get(qn('w:eastAsia')):
                rfonts.set(qn('w:eastAsia'), '宋体')

_apply_body_format()


# 2.7 清理空的标题段落（原文中存在的空 Heading）
def _clean_empty_headings():
    to_remove = []
    for p in doc.paragraphs:
        if p.style.name.startswith('Heading') and not p.text.strip():
            to_remove.append(p)
    for p in to_remove:
        el = p._element
        el.getparent().remove(el)

_clean_empty_headings()


